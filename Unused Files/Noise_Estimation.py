def dBDecrease(Np, Fp, Vp, N, F, V):
    """
    Function used to estimate the reduced noise in dB based on a few parameters.

    Input:
    ---------
    Np, number of engines of BWB
    Fp, thrust of BWB [N]
    Vp, effective exhaust velocity of BWB
    N, number of engines of conventional
    F, thrust of concentional [N]
    V, effective exhaust velocity of BWB

    Output:
    ---------
    dBL, reduced noise [dB]

    """

    # Decibel reductions (individual)
    dBLN = 10 * np.log10(Np / N)  # Number of engines
    dBLF = 10 * np.log10(Fp / F)  # Thrust
    dBLV = 10 * np.log10(Vp / V)  # Exhaust velocity

    # Total decibel reduction
    dBL = dBLN + dBLF + dBLV

    return dBL

def PNL_Engines(V_tip, gamma, R, T, HP, Nb, Dp, d, theta):
    """
    Function to estimate the perceived noise level due to the engines
    at a distance d from the aircraft

    Input:
    ---------
    V_tip, blade tip velocity [m/s]
    gamma, aerodynamic constant
    R, gas constant
    T, ambient air temperature [T]
    HP, horse power [hp]
    Nb, number of blades
    Dp, blade diameter [m]
    d, distance from observer [ft]
    theta, angle from observer [degrees]

    Output:
    ---------
    PNL, perceived noise level [dB]

    """

    # Calculate Tip Mach Number
    M_tip = V_tip / (np.sqrt(gamma * R * T))

    # Determination of Partial Level 1
    FL1 = 17.237 + (36.886 * M_tip) + (6.88 * np.log(HP))

    # Determination of Partial Level 2
    FL2 = 32.551 - (8.312 * np.log(Nb)) - (8.642 * np.log(Dp))

    # Determination of Partial Level 3
    if d < 100:
        FL3 = 16.29 - (0.5 * np.log(d))
    else:
        FL3 = 56 - (9.1202 * np.log(d))

    # Determine Directivity Correction
    DI = (4.4464 * (10 ** -11) * (theta ** 6)) - (2.1049 * (10 ** -8) * (theta ** 5)) + (
                3.56 * (10 ** -6) * (theta ** 4)) - (0.0002575 * (theta ** 3)) + (0.006073 * (theta ** 2)) + (
                     0.15363 * theta) - 8.1226

    # Number of Propellers Correction
    NC = 11  # Extrapolated

    # Overall Sound Pressure Level Determination (SPL)
    SPL = FL1 + FL2 + FL3 + DI + NC

    # Perceived Noise Level (PNL)
